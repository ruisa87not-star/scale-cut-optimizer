const reportReplacements = Object.entries({ ...english, ...reportEnglish })
  .filter(([source]) => !source.includes('{'))
  .sort(([a], [b]) => b.length - a.length);

export function translateReportText(value, language) {
  if (normalizeLanguage(language) !== 'en' || typeof value !== 'string') return value;
  let translated = value;
  for (const [source, target] of reportReplacements) translated = translated.split(source).join(target);
  return translated;
}
