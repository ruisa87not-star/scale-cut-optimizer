export function translateError(message, language) {
  const clean = String(message).replace(/^Error invoking remote method '[^']+': (?:Error: )?/, '').trim();
  if (normalizeLanguage(language) === 'zh') return engineErrors[clean] ?? clean;
  const reverse = Object.entries(engineErrors).find(([, chinese]) => chinese === clean);
  if (reverse) return reverse[0];
  const translated = createTranslator(language)(clean);
  if (translated !== clean) return translated;
  return clean
    .replace(/^(.+) 必須是非負整數。$/, (_, label) => `${createTranslator(language)(label)} must be a non-negative whole number.`)
    .replace(/^C\+\+ 引擎異常結束（代碼 (.+)）。$/, 'The C++ engine exited unexpectedly (code $1).');
}

