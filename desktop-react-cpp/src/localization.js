export function createTranslator(language) {
  return (source, parameters = {}) => {
    if (normalizeLanguage(language) === 'en' && source === '卷' && Number(parameters.count) === 1) return 'roll';
    const template = normalizeLanguage(language) === 'en' ? english[source] ?? source : source;
    return template.replace(/\{(\w+)\}/g, (match, name) => String(parameters[name] ?? match));
  };
}

